create or replace function uos_authorize_action(
  p_workspace uuid,
  p_project uuid,
  p_resource text,
  p_action text
) returns boolean language plpgsql stable security definer set search_path=public as $$
begin
  case lower(coalesce(p_resource,''))
    when 'finance' then
      return case lower(coalesce(p_action,''))
        when 'read' then uos_can_view_finance(p_workspace)
        when 'create', 'update' then uos_can_edit_finance(p_workspace)
        when 'delete', 'manage' then uos_role_rank(uos_workspace_role(p_workspace)) >= 50
        when 'export' then uos_can_export_finance(p_workspace)
        else false end;
    when 'project' then
      return case lower(coalesce(p_action,''))
        when 'read' then uos_can_read_project(p_project)
        when 'create', 'update' then uos_can_write_project(p_project)
        when 'delete' then uos_can_delete_project(p_project)
        when 'manage' then uos_can_manage_project(p_project)
        else false end;
    when 'workspace' then
      return case lower(coalesce(p_action,''))
        when 'read' then uos_can_read_workspace(p_workspace)
        when 'create', 'update' then uos_can_write_workspace(p_workspace)
        when 'delete' then uos_role_rank(uos_workspace_role(p_workspace)) >= 60
        when 'manage' then uos_can_manage_workspace(p_workspace)
        else false end;
    when 'audit' then
      return case lower(coalesce(p_action,'')) when 'read', 'export' then uos_can_manage_audit(p_workspace) else false end;
    else
      return case lower(coalesce(p_action,''))
        when 'read' then uos_can_read_workspace(p_workspace)
        when 'create', 'update' then uos_can_write_workspace(p_workspace)
        when 'delete' then uos_can_delete_workspace(p_workspace)
        when 'manage' then uos_can_manage_workspace(p_workspace)
        else false end;
  end case;
end
$$;

