create or replace function uos_role_rank(p_role text)
returns int language sql immutable as $$
  select case lower(coalesce(p_role,''))
    when 'viewer' then 10
    when 'contributor' then 20
    when 'editor' then 30
    when 'manager' then 40
    when 'admin' then 50
    when 'owner' then 60
    else 0
  end
$$;

create or replace function uos_workspace_role(p_workspace uuid, p_user uuid default auth.uid())
returns text language sql stable security definer set search_path=public as $$
  select case
    when w.owner_id = p_user then 'owner'
    else coalesce(max(m.role) filter (where m.active), 'none')
  end
  from uos_workspaces w
  left join uos_workspace_members m on m.workspace_id = w.id and m.user_id = p_user
  where w.id = p_workspace
  group by w.id, w.owner_id
$$;

create or replace function uos_is_member(p_workspace uuid)
returns boolean language sql stable security definer set search_path=public as $$
  select uos_workspace_role(p_workspace, auth.uid()) <> 'none'
$$;

create or replace function uos_can_read_workspace(p_workspace uuid)
returns boolean language sql stable security definer set search_path=public as $$
  select uos_role_rank(uos_workspace_role(p_workspace, auth.uid())) >= 10
$$;

create or replace function uos_can_write_workspace(p_workspace uuid)
returns boolean language sql stable security definer set search_path=public as $$
  select uos_role_rank(uos_workspace_role(p_workspace, auth.uid())) >= 20
