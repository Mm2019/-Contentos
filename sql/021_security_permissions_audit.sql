create or replace function uos_can_read_content_account(p_project uuid, p_account text)
returns boolean language sql stable security definer set search_path=public as $$
  select case
    when uos_can_manage_project(p_project) then true
    when not exists(select 1 from uos_content_account_permissions cap where cap.project_id=p_project and cap.content_account_id=p_account and cap.active)
      and not exists(select 1 from uos_content_account_permissions cap where cap.project_id=p_project and cap.content_account_id=p_account)
      then uos_can_read_project(p_project)
    else exists(select 1 from uos_content_account_permissions cap where cap.project_id=p_project and cap.content_account_id=p_account and cap.user_id=auth.uid() and cap.active and uos_role_rank(cap.role) >= 10)
  end
$$;

create or replace function uos_can_write_content_account(p_project uuid, p_account text)
returns boolean language sql stable security definer set search_path=public as $$
  select case
    when uos_can_manage_project(p_project) then true
    when not exists(select 1 from uos_content_account_permissions cap where cap.project_id=p_project and cap.content_account_id=p_account)
      then uos_can_write_project(p_project)
    else exists(select 1 from uos_content_account_permissions cap where cap.project_id=p_project and cap.content_account_id=p_account and cap.user_id=auth.uid() and cap.active and uos_role_rank(cap.role) >= 20)
  end
$$;

