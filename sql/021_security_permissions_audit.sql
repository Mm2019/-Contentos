-- Replace the old owner-only membership function semantics with role-aware membership.
-- Rebuild RLS policies for all current workspace-scoped tables.
do $$
declare
  r record;
  has_project boolean;
  stmt text;
  tbl text;
  excluded constant text[] := array['uos_workspace_members','uos_project_members','uos_finance_permissions','uos_content_account_permissions','uos_audit_log','uos_workspaces','uos_fin_accounts','uos_fin_categories','uos_fin_transactions','uos_fin_budgets','uos_fin_recurring','uos_fin_debts','uos_fin_savings_goals'];
begin
  for r in select distinct c.table_name
           from information_schema.columns c
           join information_schema.tables t on t.table_schema=c.table_schema and t.table_name=c.table_name
          where c.table_schema='public' and c.column_name='workspace_id' and c.table_name like 'uos_%' and t.table_type='BASE TABLE'
  loop
    tbl := r.table_name;
    if tbl = any(excluded) then continue; end if;
    has_project := exists(select 1 from information_schema.columns where table_schema='public' and table_name=tbl and column_name='project_id');
    execute format('drop policy if exists %I_read on %I',tbl,tbl);
    execute format('drop policy if exists %I_insert on %I',tbl,tbl);
    execute format('drop policy if exists %I_update on %I',tbl,tbl);
    execute format('drop policy if exists %I_delete on %I',tbl,tbl);
    if tbl='uos_projects' then
      execute format('create policy %I_read on %I for select to authenticated using (uos_can_read_project(id))',tbl,tbl);
      execute format('create policy %I_insert on %I for insert to authenticated with check (uos_can_write_workspace(workspace_id))',tbl,tbl);
      execute format('create policy %I_update on %I for update to authenticated using (uos_can_write_project(id)) with check (uos_can_write_project(id))',tbl,tbl);
      execute format('create policy %I_delete on %I for delete to authenticated using (uos_can_delete_project(id))',tbl,tbl);
    elsif has_project then
      execute format('create policy %I_read on %I for select to authenticated using (project_id is null or uos_can_read_project(project_id))',tbl,tbl);
      execute format('create policy %I_insert on %I for insert to authenticated with check (project_id is null or uos_can_write_project(project_id))',tbl,tbl);
      execute format('create policy %I_update on %I for update to authenticated using (project_id is null or uos_can_write_project(project_id)) with check (project_id is null or uos_can_write_project(project_id))',tbl,tbl);
      execute format('create policy %I_delete on %I for delete to authenticated using (project_id is null or uos_can_delete_project(project_id))',tbl,tbl);
    else
      execute format('create policy %I_read on %I for select to authenticated using (uos_can_read_workspace(workspace_id))',tbl,tbl);
      execute format('create policy %I_insert on %I for insert to authenticated with check (uos_can_write_workspace(workspace_id))',tbl,tbl);
      execute format('create policy %I_update on %I for update to authenticated using (uos_can_write_workspace(workspace_id)) with check (uos_can_write_workspace(workspace_id))',tbl,tbl);
      execute format('create policy %I_delete on %I for delete to authenticated using (uos_can_delete_workspace(workspace_id))',tbl,tbl);
    end if;
  end loop;
end $$;

