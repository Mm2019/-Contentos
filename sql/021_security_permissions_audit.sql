create or replace function uos_project_role(p_project uuid, p_user uuid default auth.uid())
returns text language sql stable security definer set search_path=public as $$
  with p as (select id, workspace_id, owner_id from uos_projects where id = p_project),
  explicit as (
    select pm.role from uos_project_members pm where pm.project_id = p_project and pm.user_id = p_user and pm.active limit 1
  )
  select case
    when p.owner_id = p_user then 'owner'
    when uos_role_rank(uos_workspace_role(p.workspace_id, p_user)) >= 50 then uos_workspace_role(p.workspace_id, p_user)
    when exists(select 1 from uos_project_members pm where pm.project_id = p_project and pm.active) then coalesce((select role from explicit), 'none')
    else uos_workspace_role(p.workspace_id, p_user)
  end
  from p
$$;

