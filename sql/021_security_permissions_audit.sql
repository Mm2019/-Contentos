-- Database-level audit trail. Client roles cannot directly write to the audit table.
create or replace function uos_audit_row_change() returns trigger language plpgsql security definer set search_path=public as $$
declare
  row_json jsonb;
  old_json jsonb;
  new_json jsonb;
  ws uuid;
  proj uuid;
  entity_id text;
  actor uuid;
begin
  old_json := case when TG_OP in ('UPDATE','DELETE') then to_jsonb(OLD) else null end;
  new_json := case when TG_OP in ('INSERT','UPDATE') then to_jsonb(NEW) else null end;
  row_json := coalesce(new_json, old_json, '{}'::jsonb);
  ws := nullif(row_json->>'workspace_id','')::uuid;
  proj := nullif(row_json->>'project_id','')::uuid;
  entity_id := coalesce(row_json->>'id', '');
  actor := auth.uid();
  insert into uos_audit_log(workspace_id,project_id,actor_id,action,entity_table,entity_id,old_values,new_values,reason,source)
  values(ws,proj,actor,TG_OP,TG_TABLE_NAME,entity_id,old_json,new_json,current_setting('uos.audit.reason',true),'database_trigger');
  return coalesce(NEW, OLD);
end $$;

create or replace function uos_audit_workspace_change() returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into uos_audit_log(workspace_id,actor_id,action,entity_table,entity_id,old_values,new_values,reason,source)
  values(coalesce(NEW.id,OLD.id),auth.uid(),TG_OP,TG_TABLE_NAME,(coalesce(NEW.id,OLD.id))::text,
         case when TG_OP in ('UPDATE','DELETE') then to_jsonb(OLD) else null end,
         case when TG_OP in ('INSERT','UPDATE') then to_jsonb(NEW) else null end,
         current_setting('uos.audit.reason',true),'database_trigger');
  return coalesce(NEW,OLD);
end $$;

drop trigger if exists trg_uos_audit_workspaces on uos_workspaces;
create trigger trg_uos_audit_workspaces after insert or update or delete on uos_workspaces
for each row execute function uos_audit_workspace_change();

do $$
declare r record;
begin
  for r in select distinct c.table_name
           from information_schema.columns c
           join information_schema.tables t on t.table_schema=c.table_schema and t.table_name=c.table_name
          where c.table_schema='public' and c.column_name='workspace_id' and c.table_name like 'uos_%'
            and t.table_type='BASE TABLE'
            and c.table_name not in ('uos_audit_log')
  loop
    execute format('drop trigger if exists %I on %I', 'trg_uos_audit_'||r.table_name, r.table_name);
    execute format('create trigger %I after insert or update or delete on %I for each row execute function uos_audit_row_change()', 'trg_uos_audit_'||r.table_name, r.table_name);
  end loop;
end $$;

