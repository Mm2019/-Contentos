-- Phase 19 — Versioning + Migration + Backup + Restore + Rollback
-- Unified OS recovery control plane. Existing ContentOS recovery remains authoritative and is not duplicated here.
create extension if not exists pgcrypto;

create table if not exists uos_schema_registry (
  id boolean primary key default true check (id),
  current_version text not null,
  minimum_compatible_version text not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create table if not exists uos_migration_log (
  id uuid primary key default gen_random_uuid(),
  version text not null unique,
  migration_name text not null,
  checksum text not null,
  status text not null default 'applied' check (status in ('pending','applied','failed','rolled_back')),
  applied_at timestamptz not null default now(),
  applied_by uuid references auth.users(id) on delete set null,
  notes text
);

create table if not exists uos_recovery_snapshots (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references uos_workspaces(id) on delete cascade,
  snapshot_type text not null default 'manual' check (snapshot_type in ('protective','manual','pre_migration','export')),
  schema_version text not null,
  created_by uuid references auth.users(id) on delete set null,
  status text not null default 'ready' check (status in ('creating','ready','failed','restored','rolled_back')),
  table_count integer not null default 0,
  row_count bigint not null default 0,
  manifest jsonb not null default '{}'::jsonb,
  checksum text,
  restored_to_workspace_id uuid references uos_workspaces(id) on delete set null,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  notes text
);

create table if not exists uos_recovery_items (
  id bigint generated by default as identity primary key,
  snapshot_id uuid not null references uos_recovery_snapshots(id) on delete cascade,
  table_name text not null,
  row_count bigint not null default 0,
  payload jsonb not null default '[]'::jsonb,
  checksum text not null,
  unique(snapshot_id, table_name)
);

create table if not exists uos_recovery_runs (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid references uos_workspaces(id) on delete set null,
  snapshot_id uuid references uos_recovery_snapshots(id) on delete set null,
  restored_to_workspace_id uuid references uos_workspaces(id) on delete set null,
  action text not null check (action in ('snapshot','export','restore','rollback','compatibility_check')),
  status text not null default 'started' check (status in ('started','success','failed')),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  actor_id uuid references auth.users(id) on delete set null,
  summary jsonb not null default '{}'::jsonb,
  error text
);

create index if not exists idx_uos_migration_log_applied on uos_migration_log(applied_at desc);
create index if not exists idx_uos_recovery_snapshots_ws on uos_recovery_snapshots(workspace_id, created_at desc);
create index if not exists idx_uos_recovery_items_snapshot on uos_recovery_items(snapshot_id);
create index if not exists idx_uos_recovery_runs_ws on uos_recovery_runs(workspace_id, started_at desc);

insert into uos_schema_registry(id,current_version,minimum_compatible_version,updated_by)
values(true,'022','010',auth.uid())
on conflict (id) do update set current_version=excluded.current_version, minimum_compatible_version=excluded.minimum_compatible_version, updated_at=now(), updated_by=auth.uid();

insert into uos_migration_log(version,migration_name,checksum,status,applied_by,notes)
values('022','versioning-recovery','phase19-control-plane','applied',auth.uid(),'Unified OS recovery metadata. ContentOS recovery remains external/authoritative.')
on conflict (version) do update set status='applied', checksum=excluded.checksum, applied_at=now(), applied_by=auth.uid(), notes=excluded.notes;

